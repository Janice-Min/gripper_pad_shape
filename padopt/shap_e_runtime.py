"""Keep all torch/Shap-E imports out of CPU geometry and evaluation tools."""
from pathlib import Path
import hashlib
import inspect
import sys


def initialize(cfg, source=None, device_name="auto", allow_modified_mc=False, decoder=True):
    repo = Path(source or cfg["shap_e_dir"]).resolve()
    if not (repo / "shap_e" / "diffusion" / "sample.py").is_file():
        raise FileNotFoundError("Pass --shap-e-dir pointing to the directory that CONTAINS shap_e/ : " + str(repo))
    sys.path.insert(0, str(repo))
    import torch
    import shap_e
    import shap_e.rendering.mc as mc
    from shap_e.models.download import load_model, load_config
    from shap_e.diffusion.gaussian_diffusion import diffusion_from_config
    imported = Path(shap_e.__file__).resolve()
    if repo not in imported.parents:
        raise RuntimeError("A different Shap-E is already imported: " + str(imported))
    source_code = inspect.getsource(mc.marching_cubes)
    if "sdf_min" in source_code and "threshold" in source_code and not allow_modified_mc:
        raise RuntimeError("This Shap-E changes the marching-cubes isovalue. Use the uploaded from_johnson copy (zero isovalue), or pass --allow-modified-mc explicitly.")
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu") if device_name == "auto" else torch.device(device_name)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but is unavailable.")
    cache = str(Path(cfg["cache_dir"]).resolve())
    model = load_model("text300M", device=device, cache_dir=cache)
    model.eval().requires_grad_(False)
    diffusion = diffusion_from_config(load_config("diffusion", cache_dir=cache))
    xm = load_model("transmitter", device=device, cache_dir=cache) if decoder else None
    if xm is not None:
        xm.eval().requires_grad_(False)
    runtime = {"torch": torch, "device": device, "model": model, "diffusion": diffusion, "xm": xm,
               "provenance": {"source_root": str(repo), "marching_cubes_sha256": hashlib.sha256(source_code.encode()).hexdigest(),
                              "modified_marching_cubes_allowed": allow_modified_mc, "torch_version": torch.__version__,
                              "source_files_sha256": {name: hashlib.sha256((repo / name).read_bytes()).hexdigest() for name in (
                                  "shap_e/diffusion/sample.py", "shap_e/diffusion/k_diffusion.py", "shap_e/models/generation/transformer.py")}}}
    return runtime


def load_tensor(torch, path):
    # Only tensor/primitive files generated by this package are accepted.
    return torch.load(path, map_location="cpu", weights_only=True)


def seed_everything(torch, seed):
    import random
    import numpy as np
    random.seed(seed)
    np.random.seed(seed % (2 ** 32))
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
