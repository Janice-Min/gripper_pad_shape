import argparse
from pathlib import Path
import shutil
from padopt.common import read_config, save_json, source_signature
from padopt.geometry import flat_pad, save_pad
from padopt.xml_model import build_xml


def main():
    p = argparse.ArgumentParser(description="Create a flat pad control (explicitly NOT generated by Shap-E).")
    p.add_argument("--config", default="config.json")
    p.add_argument("--thickness-mm", type=float, default=3.5)
    args = p.parse_args()
    cfg = read_config(args.config)
    if not cfg["pad"]["thickness_min_mm"] <= args.thickness_mm <= cfg["pad"]["thickness_max_mm"]:
        p.error("baseline thickness must fall within the configured bounds")
    parent = Path(cfg["output_dir"]) / "baselines"
    parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(cfg["base_xml"], parent / "bare_gripper.xml")
    folder = parent / "pad_flat"
    stats = save_pad(folder, cfg, *flat_pad(cfg, args.thickness_mm))
    save_json(folder / "metadata.json", {"candidate_id": "pad_flat", "source": "flat_baseline", "source_signature": source_signature(cfg), **stats})
    print(build_xml(cfg, folder))


if __name__ == "__main__":
    main()
